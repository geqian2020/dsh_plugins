import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {Context} from '../vendor/installed-runtime/node_modules/@deepseek-ai/cordis/lib/index.js';
import {SystemPrompt,renderPrompt} from '../vendor/installed-runtime/node_modules/@deepseek-ai/dsh-system-prompt/lib/index.js';
import {ToolRuntime,defineTool} from '../vendor/installed-runtime/node_modules/@deepseek-ai/dsh-tools/lib/index.js';
import {createScope,scopeTarget} from '../vendor/installed-runtime/node_modules/@deepseek-ai/dsh-scope/lib/index.js';
import {memoryToolGuard,createPolicy} from '../src/isolation.mjs';
test('installed DSH tool registry enforces bidirectional visibility and execution',async()=>{
 const ctx=new Context();
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'book-host-'));
 const out=path.resolve('vendor/installed-runtime/book-plugin');
 fs.cpSync(path.resolve('packages/book-companion'),out,{recursive:true});
 const plugin=await import('../vendor/installed-runtime/book-plugin/index.mjs');
 let bookScope,mainScope,presetScope;
 try{
  new SystemPrompt(ctx,{});new ToolRuntime(ctx,{});
  assert.throws(()=>plugin.apply(ctx,{dataDir:dir}),/exclusion is required/);
  ctx.provide('bookMemoryIsolation',{version:1,excludes:createPolicy()});
  let mainCalls=0;
  ctx.tools.register(defineTool({name:'mcp__openviking__remember',description:'main memory',parameters:{},output:{schema:{type:'string'},render:(_a,v)=>[{type:'text',text:v}]},execute(){mainCalls++;return 'MAIN_SECRET';}}));
  ctx.tools.guard(memoryToolGuard(createPolicy()));
  const book={session:{header:{id:'book-1',agentPreset:'book-companion'}}};
  const main={session:{header:{id:'main-1',agentPreset:'standard'}}};
  const presetKey={};presetScope=createScope(ctx,presetKey);
  bookScope=createScope(ctx,book,{parent:presetKey});book.ctx=bookScope.ctx;
  mainScope=createScope(ctx,main);main.ctx=mainScope.ctx;
  plugin.apply(presetScope.ctx,{dataDir:dir});
  await ctx.serial(scopeTarget(ctx,book),'agent/created',{agent:book,source:'test'});
  ctx.systemPrompt.section({name:'main-secret-persona',order:10,text:'MAIN_PERSONA_SENTINEL'});
  const bookPrompt=renderPrompt(await ctx.systemPrompt.assemble({scope:book}));
  assert.match(bookPrompt,/阅读搭子/);assert.equal(bookPrompt.includes('MAIN_PERSONA_SENTINEL'),false);
  assert.equal(renderPrompt(await ctx.systemPrompt.assemble({scope:main})).includes('MAIN_PERSONA_SENTINEL'),true);
  assert.deepEqual(ctx.tools.schemas(book).map(x=>x.name).sort(),['book_discover','book_episode','book_forget','book_import_transcript','book_read_article','book_recall','book_remember','book_review','book_thread','book_transcribe']);
  assert.deepEqual(ctx.tools.schemas(main).map(x=>x.name),['mcp__openviking__remember']);
  const call=(agent,name,args={})=>ctx.tools.execute({agent,name,arguments:args,callId:Math.random().toString(),signal:new AbortController().signal});
  assert.equal((await call(book,'mcp__openviking__remember')).isError,true);
  assert.equal(mainCalls,0);
  const saved=await call(book,'book_remember',{kind:'user-view',text:'BOOK_SENTINEL',source:'test-user'});
  assert.equal(saved.isError,false,JSON.stringify(saved));
  assert.equal((await call(main,'book_recall',{query:'BOOK_SENTINEL'})).isError,true);
  assert.equal((await call(book,'book_recall',{query:'BOOK_SENTINEL'})).value[0].text,'BOOK_SENTINEL');
  assert.equal((await call(main,'mcp__openviking__remember')).value,'MAIN_SECRET');
  assert.equal(mainCalls,1);
  await bookScope.dispose();await mainScope.dispose();
 }finally{await bookScope?.dispose();await mainScope?.dispose();await presetScope?.dispose();fs.rmSync(dir,{recursive:true,force:true});}
});
